// Builds the game's data from the supplied Monarque source files (data-src/).
//   data-src/*.json  ->  src/data/cards.json (83-record unified registry)
//                     ->  src/data/monarque.generated.js (plain ES module, usable by Node tests and the browser bundle)
// The combat engine dispatches on its original effect IDs. The supplied data uses Monarque effect IDs, so each record
// keeps the engine ID in `effectId` and the supplied ID in `monarqueEffectId`. That mapping is the ONLY bridge.
//   node scripts/build-monarque-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, 'data-src', f), 'utf8'));

export const ENGINE_EFFECT = {
  // Edicts (Monarque's own wild cards, and the family of every contender power)
  LAST_DRAUGHT: 'SENZU', THE_RECKONING: 'FINAL_ATONEMENT', INVERTED_REALM: 'OTHER_WORLD', BLINDING_ECLIPSE: 'SOLAR_FLARE',
  ORACLE_GAZE: 'SCOUTER', MONARQUE_BOON: 'SHENRON_WISH', BINDING_SEAL: 'MAFUBA', UNRAVELING: 'CURSE',
  // Whims (round-start interventions)
  CULLING_DRAFT: 'DRAGON_BALL_DRAFT', SILENT_TITHE: 'SACRED_AUCTION', WHETSTONE_RITE: 'TRAINING_ARC', DEBT_CALLED: 'BOUNTY_HUNT',
  TRIAL_SET: 'SIDE_QUEST', HOLLOW_HOUR: 'TIME_CHAMBER', RITE_OF_EXCHANGE: 'DIVINE_SWAP', UNRAVELING_LAID: 'CURSE_INJECTION',
  // Omens (special rounds)
  OPEN_EYE: 'PUBLIC_FORECAST', HUSHED_CROWNS: 'NO_APEX', THE_WEIGHING: 'TOTAL_MIGHT', REVERSED_HOUR: 'BACKWARDS',
  BOON_ROUND: 'WISH_ROUND', DEBT_DOUBLED: 'HIGH_STAKES', DESPERATE_SURGE: 'ZENKAI',
};

const edicts = read('monarque_edict_cards_8.json');
const whims = read('monarque_whim_cards_8.json');
const omens = read('monarque_omen_cards_7.json');
const bound = read('bound_being_cards_60.json');
const contenders = read('contender_cards_32.json').map((c) => ({ ...c, powerImage: c.image })); // a contender's power art is its own portrait
// Contenders are fighters, not playable cards: they carry no Power, Rank or power group (those belong to bound beings only).
for (const c of contenders) for (const k of ['power', 'rank', 'powerGroup']) if (k in c) throw new Error(`Contender ${c.id} must not define \`${k}\``);

const eng = (id) => { const e = ENGINE_EFFECT[id]; if (!e) throw new Error(`No engine effect mapped for ${id}`); return e; };
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const records = [
  // The supplied file names the lowest tier ELUSIVE; the engine keys on WEAK (Last Stand cards). Keep the engine id, show 'Elusive' via L().
  ...bound.map((c) => ({ ...c, tier: c.tier === 'ELUSIVE' ? 'WEAK' : c.tier, powerGroup: c.powerGroup === 'ELUSIVE' ? 'WEAK' : c.powerGroup })),
  ...edicts.map((c) => ({
    id: c.id, character: c.title, form: 'Edict', title: c.form, description: c.description, flavor: c.flavor, power: null, rank: null, powerGroup: null,
    series: 'SPECIAL', category: 'WILDCARD', rarity: 'SPECIAL', image: c.image, type: 'WILDCARD', cardClass: c.cardClass, effectId: eng(c.effectId), monarqueEffectId: c.effectId,
    unique: true, rules: c.rules, finaleBouts: c.finaleBouts, monarqueLines: c.monarqueLines, soundCue: c.soundCue, artDirection: c.artDirection,
  })),
  ...whims.map((c) => ({
    id: c.id, character: 'Monarque', form: c.form, title: c.title, description: c.description, flavor: c.flavor, power: null, rank: null, powerGroup: null,
    series: 'EVENT', category: 'GM_POWER', rarity: 'EVENT', image: c.image, type: 'GM_POWER', cardClass: c.cardClass, effectId: eng(c.effectId), monarqueEffectId: c.effectId,
    weight: c.weight, rules: c.rules, telegraph: c.telegraph, soundCue: c.soundCue, artDirection: c.artDirection,
  })),
  ...omens.map((c) => ({
    id: c.id, character: 'Omen', form: c.form, title: c.title, description: c.description, flavor: c.flavor, power: null, rank: null, powerGroup: null,
    series: 'EVENT', category: 'CRAZY_ROUND', rarity: 'EVENT', image: c.image, type: 'CRAZY_ROUND', cardClass: c.cardClass, effectId: eng(c.effectId), monarqueEffectId: c.effectId,
    duration: c.duration, weight: c.weight, rules: c.rules, soundCue: c.soundCue, artDirection: c.artDirection,
  })),
];
fs.writeFileSync(path.join(root, 'src/data/cards.json'), `${JSON.stringify(records, null, 1)}\n`);

const gen = `// GENERATED by scripts/build-monarque-data.mjs from data-src/. Do not edit by hand.
export const ENGINE_EFFECT = ${JSON.stringify(ENGINE_EFFECT, null, 1)};
export const EDICTS = ${JSON.stringify(edicts, null, 1)};
export const WHIMS = ${JSON.stringify(whims, null, 1)};
export const OMENS = ${JSON.stringify(omens, null, 1)};
export const CONTENDERS = ${JSON.stringify(contenders, null, 1)};
`;
fs.writeFileSync(path.join(root, 'src/data/monarque.generated.js'), gen);
console.log(`cards.json: ${records.length} records (${bound.length} bound beings, ${edicts.length} edicts, ${whims.length} whims, ${omens.length} omens); ${contenders.length} contenders -> monarque.generated.js`);
void slug;
